class Command(BaseCommand):
    help = "Load the public website content (official Jamia content + clearly marked samples)."

    def add_arguments(self, parser):
        parser.add_argument("--reset", action="store_true", help="Delete existing website content first")

    @transaction.atomic
    def handle(self, *args, reset=False, **opts):
        if reset:
            for model in (m.MeritListEntry, m.MeritList, m.Faculty, m.Program, m.GalleryItem, m.Department, m.News, m.Announcement,
                          m.CalendarItem, m.Document, m.Testimonial, m.Faq, m.Page, m.WebsiteSettings):
                model.objects.all().delete()
        elif m.WebsiteSettings.objects.exists():
            self.stdout.write("Website content already exists — use --reset to reload it.")
            return
        data = json.loads((SEED / "jamia_content.json").read_text(encoding="utf-8"))
        self.settings(data)
        depts = self.departments(data)
        progs = self.programs(data, depts)
        self.faculty(data, depts)
        self.content(data, depts)
        self.events()
        self.admissions(progs)
        self.stdout.write(self.style.SUCCESS(
            f"Website content loaded: {len(depts)} departments, {len(progs)} programs, {m.Faculty.objects.count()} faculty."))

