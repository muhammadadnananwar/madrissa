    def settings(self, data):
        s = data["SETTINGS"]
        swap = {"__HERO__": scene_path("hero"), "__ABOUT__": scene_path("about"), "__LIBRARY__": scene_path("facility-library"),
                "__CLASSROOM__": scene_path("facility-classroom"), "__BOARDING__": scene_path("facility-boarding")}
        s = json.loads(json.dumps(s), object_hook=lambda o: {k: swap.get(v, v) if isinstance(v, str) else v for k, v in o.items()})
        prospectus = self.pdf_document("UMS Prospectus", "prospectus")
        s["admissions"]["prospectusUrl"] = f"/api/site/public/documents/{prospectus.pk}/download"
        m.WebsiteSettings.objects.all().delete()
        m.WebsiteSettings.objects.create(
            university_name="University of Muhammadia Saifia", university_name_ur=s["universityNameUr"], short_name="UMS",
            tagline=s["tagline"], tagline_ur=s["taglineUr"], hero=s["hero"], admission_banner=s["admissionBanner"],
            admissions_open=s["admissionsOpen"], current_session=s["currentSession"], stats=s["stats"], about=s["about"],
            vice_chancellor=s["viceChancellor"], chancellor=s["chancellor"], leadership=s["leadership"], why_choose=s["whyChoose"],
            campus_facilities=s["campusFacilities"], societies=s["societies"], admissions=s["admissions"], contact=s["contact"],
            social={"facebook": "", "instagram": "", "twitter": "", "youtube": "", "linkedin": ""},
            whatsapp_number=s.get("whatsappNumber", ""), seo=s["seo"], footer_text=s["footerText"])
        self.patron_photo()

    def patron_photo(self):
        """Photo of the patron, Hazrat Mian Muhammad Saifi Hanafi: head's message + first leadership entry."""
        if not PATRON_PHOTO.is_file():
            return
        site = m.WebsiteSettings.load()
        with PATRON_PHOTO.open("rb") as fh:
            site.vice_chancellor_photo.save("patron.jpg", File(fh), save=False)
        for person in site.leadership:
            if "Saifi Hanafi" in person.get("name", ""):
                person["photo"] = site.vice_chancellor_photo.url
        site.save()

    def departments(self, data):
        out = {}
        for i, d in enumerate(data["DEPARTMENTS"]):
            out[d["code"]] = m.Department(
                name=d["name"], name_ur=d.get("nameUr", ""), code=d["code"], faculty=d.get("faculty", ""),
                short_description=d.get("shortDescription", ""), short_description_ur=d.get("shortDescriptionUr", ""),
                introduction=d.get("introduction") or f"{d.get('shortDescription', '')}\n\n{data['P']} Add a detailed introduction of "
                                                      "this department in the portal (Website > Departments).",
                head_name=d.get("headName", ""), head_designation=d.get("headDesignation", ""),
                order=i)
            attach(out[d["code"]], "image", DEPT_SCENE.get(d["code"], "about"))
            out[d["code"]].save()
        return out

