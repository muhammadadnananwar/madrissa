def attach(obj, field, scene):
    """Save a seed image into an ImageField (no save of the model): photos/<scene>.jpg if present, else scenes/<scene>.jpg."""
    path = PHOTOS / f"{scene}.jpg"
    if not path.is_file():
        path = SCENES / f"{scene}.jpg"
    with path.open("rb") as fh:
        getattr(obj, field).save(f"{scene}.jpg", File(fh), save=False)


def scene_path(scene):
    """Copy a scene into media and return its /media/... path (for images referenced from the settings JSON)."""
    name = f"website/scenes/{scene}.jpg"
    if default_storage.exists(name):
        default_storage.delete(name)
    with (SCENES / f"{scene}.jpg").open("rb") as fh:
        default_storage.save(name, File(fh))
    return settings.MEDIA_URL + name


